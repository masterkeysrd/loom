func TestMemoryStore_Namespaces(t *testing.T) {
	ctx := context.Background()
	store := newTestStore(t)

	doc1 := document.New("apple fruit").WithID("doc-ns1")
	doc2 := document.New("apple tree").WithID("doc-ns2")

	_, err := store.Add(ctx, []document.Document{doc1}, vectorstore.WithAddNamespace("ns1"))
	if err != nil {
		t.Fatalf("Add ns1 failed: %v", err)
	}
	_, err = store.Add(ctx, []document.Document{doc2}, vectorstore.WithAddNamespace("ns2"))
	if err != nil {
		t.Fatalf("Add ns2 failed: %v", err)
	}

	// Search in ns1
	res1, err := store.Search(ctx, "query apple", 10, vectorstore.WithNamespace("ns1"))
	if err != nil {
		t.Fatalf("Search ns1 failed: %v", err)
	}
	if len(res1) != 1 || res1[0].ID != "doc-ns1" {
		t.Fatalf("expected doc-ns1 in ns1, got %v", res1)
	}

	// Search in default ns
	resDef, err := store.Search(ctx, "query apple", 10)
	if err != nil {
		t.Fatalf("Search default failed: %v", err)
	}
	if len(resDef) != 0 {
		t.Fatalf("expected 0 results in default ns, got %v", resDef)
	}
}

func TestMemoryStore_MinScoreAndFilter(t *testing.T) {
	ctx := context.Background()
	store := newTestStore(t)

	docs := []document.Document{
		document.New("apple fruit", map[string]any{"type": "fruit", "rating": 5}).WithID("apple-1"),
		document.New("apple tree", map[string]any{"type": "plant", "rating": 5}).WithID("apple-2"),
		document.New("sports car", map[string]any{"type": "vehicle", "rating": 5}).WithID("car-1"),
	}

	if _, err := store.Add(ctx, docs); err != nil {
		t.Fatalf("Add failed: %v", err)
	}

	// Filter by type: fruit
	resFilter, err := store.Search(ctx, "query apple", 10, vectorstore.WithFilter(map[string]any{"type": "fruit"}))
	if err != nil {
		t.Fatalf("Search failed: %v", err)
	}
	if len(resFilter) != 1 || resFilter[0].ID != "apple-1" {
		t.Fatalf("expected only apple-1, got %v", resFilter)
	}

	// MinScore threshold: sports car has cosine similarity 0 with query apple
	resScore, err := store.Search(ctx, "query apple", 10, vectorstore.WithMinScore(0.5))
	if err != nil {
		t.Fatalf("Search failed: %v", err)
	}
	if len(resScore) != 2 { // apple fruit (1.0) and apple tree (~0.99)
		t.Fatalf("expected 2 results above min score 0.5, got %d", len(resScore))
	}
}

func TestMemoryStore_Delete(t *testing.T) {
	ctx := context.Background()
	store := newTestStore(t)

	docs := []document.Document{
		document.New("apple fruit").WithID("doc-1"),
		document.New("sports car").WithID("doc-2"),
	}

	if _, err := store.Add(ctx, docs); err != nil {
		t.Fatalf("Add failed: %v", err)
	}

	// Delete doc-1
	if err := store.Delete(ctx, []string{"doc-1"}); err != nil {
		t.Fatalf("Delete failed: %v", err)
	}

	res, err := store.Search(ctx, "query apple", 10)
	if err != nil {
		t.Fatalf("Search failed: %v", err)
	}
	for _, r := range res {
		if r.ID == "doc-1" {
			t.Errorf("doc-1 was not deleted")
		}
	}

	// Delete empty slice is no-op
	if err := store.Delete(ctx, nil); err != nil {
		t.Errorf("Delete nil returned err: %v", err)
	}
}

func TestMemoryStore_Concurrency(t *testing.T) {
	ctx := context.Background()
	store := newTestStore(t)

	var wg sync.WaitGroup
	workers := 10
	iterations := 20

	for w := range workers {
		wg.Add(1)
		go func(workerID int) {
			defer wg.Done()
			for i := range iterations {
				docID := fmt.Sprintf("doc-%d-%d", workerID, i)
				_, _ = store.Add(ctx, []document.Document{
					document.New("apple fruit").WithID(docID),
				})

				_, _ = store.Search(ctx, "query apple", 5)

				if i%2 == 0 {
					_ = store.Delete(ctx, []string{docID})
				}
			}
		}(w)
	}

	wg.Wait()
}

