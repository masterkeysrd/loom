type deterministicProvider struct{}

func (d deterministicProvider) Name() string { return "deterministic" }

func (d deterministicProvider) Embed(ctx context.Context, req *embedding.Request) (*embedding.Response, error) {
	embeddings := make([]embedding.Vector, len(req.Inputs))
	for i, inp := range req.Inputs {
		text := inp.Text
		vec := embedding.Vector{0.1, 0.1, 0.1, 0.1}
		switch text {
		case "apple fruit":
			vec = embedding.Vector{1.0, 0.0, 0.0, 0.0}
		case "apple tree":
			vec = embedding.Vector{0.9, 0.1, 0.0, 0.0}
		case "banana fruit":
			vec = embedding.Vector{0.8, 0.2, 0.0, 0.0}
		case "sports car":
			vec = embedding.Vector{0.0, 0.0, 1.0, 0.0}
		case "query apple":
			vec = embedding.Vector{1.0, 0.0, 0.0, 0.0}
		case "query car":
			vec = embedding.Vector{0.0, 0.0, 1.0, 0.0}
		}
		embeddings[i] = vec
	}
	return &embedding.Response{
		Model:      req.Model,
		Embeddings: embeddings,
	}, nil
}

func newTestStore(t *testing.T) (*sqlite.Store, *sql.DB) {
	t.Helper()
	db, err := sql.Open("sqlite", ":memory:")
	if err != nil {
		t.Fatalf("failed to open sqlite in-memory db: %v", err)
	}

	model, err := embedding.NewModel(deterministicProvider{}, "test-embed", nil)
	if err != nil {
		t.Fatalf("failed to create embedding model: %v", err)
	}

	store, err := sqlite.New(db, model)
	if err != nil {
		t.Fatalf("failed to create sqlite store: %v", err)
	}

	return store, db
}

func TestSQLiteStore_BasicAddAndSearch(t *testing.T) {
	ctx := context.Background()
	store, db := newTestStore(t)
	defer db.Close()

	docs := []document.Document{
		document.New("apple fruit", map[string]any{"type": "fruit", "price": 10}).WithID("doc-1"),
		document.New("banana fruit", map[string]any{"type": "fruit", "price": 5}).WithID("doc-2"),
		document.New("sports car", map[string]any{"type": "vehicle"}).WithID("doc-3"),
	}

	ids, err := store.Add(ctx, docs)
	if err != nil {
		t.Fatalf("Add failed: %v", err)
	}
	if len(ids) != 3 || ids[0] != "doc-1" {
		t.Fatalf("unexpected ids: %v", ids)
	}

	// Search for apple
	results, err := store.Search(ctx, "query apple", 2)
	if err != nil {
		t.Fatalf("Search failed: %v", err)
	}
	if len(results) != 2 {
		t.Fatalf("expected 2 results, got %d", len(results))
	}
	if results[0].ID != "doc-1" {
		t.Errorf("expected doc-1 as top match, got %s", results[0].ID)
	}
	if results[0].Score <= results[1].Score {
		t.Errorf("expected sorted scores, got %v <= %v", results[0].Score, results[1].Score)
	}
	if results[0].Metadata["price"] != float64(10) && results[0].Metadata["price"] != int64(10) {
		t.Errorf("expected metadata preserved, got %v", results[0].Metadata)
	}

	// Upsert: update doc-1 content and metadata
	updateDoc := document.New("apple fruit", map[string]any{"type": "fruit", "price": 12}).WithID("doc-1")
	if _, err := store.Add(ctx, []document.Document{updateDoc}); err != nil {
		t.Fatalf("upsert failed: %v", err)
	}
	resUpdated, err := store.Search(ctx, "query apple", 1)
	if err != nil {
		t.Fatalf("Search failed: %v", err)
	}
	if len(resUpdated) != 1 || resUpdated[0].ID != "doc-1" {
		t.Fatalf("expected doc-1, got %v", resUpdated)
	}
	if resUpdated[0].Metadata["price"] != float64(12) {
		t.Errorf("expected updated price 12, got %v", resUpdated[0].Metadata["price"])
	}
}

