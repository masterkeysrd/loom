func TestSQLiteStore_Namespaces(t *testing.T) {
	ctx := context.Background()
	store, db := newTestStore(t)
	defer db.Close()

	doc1 := document.New("apple fruit").WithID("doc-ns1")
	doc2 := document.New("apple tree").WithID("doc-ns2")

	_, err := store.Add(ctx, []document.Document{doc1}, vectorstore.WithAddNamespace("ns1"))
	if err != nil {
		t.Fatalf("Add ns1 failed: %v", err)
	}
	_, err = store.Add(ctx, []document.Document{doc2}, vectorstore.WithAddNamespace("ns2"))
	if err != nil {
		t.Fatalf("Add ns2 failed: %v", err)
	}

	// Search in ns1
	res1, err := store.Search(ctx, "query apple", 10, vectorstore.WithNamespace("ns1"))
	if err != nil {
		t.Fatalf("Search ns1 failed: %v", err)
	}
	if len(res1) != 1 || res1[0].ID != "doc-ns1" {
		t.Fatalf("expected doc-ns1 in ns1, got %v", res1)
	}

	// Search in default
	resDef, err := store.Search(ctx, "query apple", 10)
	if err != nil {
		t.Fatalf("Search default failed: %v", err)
	}
	if len(resDef) != 0 {
		t.Fatalf("expected 0 results in default ns, got %v", resDef)
	}
}

func TestSQLiteStore_MinScoreAndFilter(t *testing.T) {
	ctx := context.Background()
	store, db := newTestStore(t)
	defer db.Close()

	docs := []document.Document{
		document.New("apple fruit", map[string]any{"type": "fruit", "qty": 100}).WithID("apple-1"),
		document.New("apple tree", map[string]any{"type": "plant", "qty": 5}).WithID("apple-2"),
		document.New("sports car", map[string]any{"type": "vehicle", "qty": 1}).WithID("car-1"),
	}

	if _, err := store.Add(ctx, docs); err != nil {
		t.Fatalf("Add failed: %v", err)
	}

	// Filter with int qty matching JSON unmarshaled float64 qty
	resFilter, err := store.Search(ctx, "query apple", 10, vectorstore.WithFilter(map[string]any{"type": "fruit", "qty": 100}))
	if err != nil {
		t.Fatalf("Search failed: %v", err)
	}
	if len(resFilter) != 1 || resFilter[0].ID != "apple-1" {
		t.Fatalf("expected only apple-1, got %v", resFilter)
	}

	// MinScore threshold
	resScore, err := store.Search(ctx, "query apple", 10, vectorstore.WithMinScore(0.5))
	if err != nil {
		t.Fatalf("Search failed: %v", err)
	}
	if len(resScore) != 2 {
		t.Fatalf("expected 2 results above 0.5, got %d", len(resScore))
	}
}

