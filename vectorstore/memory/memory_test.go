type deterministicProvider struct{}

func (d deterministicProvider) Name() string { return "deterministic" }

func (d deterministicProvider) Embed(ctx context.Context, req *embedding.Request) (*embedding.Response, error) {
	embeddings := make([]embedding.Vector, len(req.Inputs))
	for i, inp := range req.Inputs {
		text := inp.Text
		// Create a 4-dimensional vector based on simple keywords for deterministic cosine similarities
		vec := embedding.Vector{0.1, 0.1, 0.1, 0.1}
		switch text {
		case "apple fruit":
			vec = embedding.Vector{1.0, 0.0, 0.0, 0.0}
		case "apple tree":
			vec = embedding.Vector{0.9, 0.1, 0.0, 0.0}
		case "banana fruit":
			vec = embedding.Vector{0.8, 0.2, 0.0, 0.0}
		case "sports car":
			vec = embedding.Vector{0.0, 0.0, 1.0, 0.0}
		case "race car":
			vec = embedding.Vector{0.0, 0.0, 0.9, 0.1}
		case "query apple":
			vec = embedding.Vector{1.0, 0.0, 0.0, 0.0}
		case "query car":
			vec = embedding.Vector{0.0, 0.0, 1.0, 0.0}
		}
		embeddings[i] = vec
	}
	return &embedding.Response{
		Model:      req.Model,
		Embeddings: embeddings,
	}, nil
}

func newTestStore(t *testing.T) *memory.Store {
	t.Helper()
	model, err := embedding.NewModel(deterministicProvider{}, "test-embed", nil)
	if err != nil {
		t.Fatalf("failed to create embedding model: %v", err)
	}
	return memory.New(model)
}

func TestMemoryStore_BasicAddAndSearch(t *testing.T) {
	ctx := context.Background()
	store := newTestStore(t)

	docs := []document.Document{
		document.New("apple fruit", map[string]any{"type": "fruit"}).WithID("doc-1"),
		document.New("banana fruit", map[string]any{"type": "fruit"}).WithID("doc-2"),
		document.New("sports car", map[string]any{"type": "vehicle"}).WithID("doc-3"),
	}

	ids, err := store.Add(ctx, docs)
	if err != nil {
		t.Fatalf("Add failed: %v", err)
	}
	if len(ids) != 3 || ids[0] != "doc-1" {
		t.Fatalf("unexpected ids: %v", ids)
	}

	// Search for apple
	results, err := store.Search(ctx, "query apple", 2)
	if err != nil {
		t.Fatalf("Search failed: %v", err)
	}
	if len(results) != 2 {
		t.Fatalf("expected 2 results, got %d", len(results))
	}
	if results[0].ID != "doc-1" {
		t.Errorf("expected doc-1 top match, got %s", results[0].ID)
	}
	if results[0].Score <= results[1].Score {
		t.Errorf("expected results sorted descending by score: %v vs %v", results[0].Score, results[1].Score)
	}

	// Search with k <= 0
	resultsZero, err := store.Search(ctx, "query apple", 0)
	if err != nil || resultsZero != nil {
		t.Errorf("expected nil results for k=0, got %v, err=%v", resultsZero, err)
	}

	// Add empty docs
	emptyIds, err := store.Add(ctx, nil)
	if err != nil || emptyIds != nil {
		t.Errorf("expected nil for empty Add, got %v, err=%v", emptyIds, err)
	}
}

